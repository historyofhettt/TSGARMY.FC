CREATE TABLE team_staff (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  teamId BIGINT UNSIGNED NOT NULL,
  name VARCHAR(255) NOT NULL,
  role VARCHAR(128) NOT NULL DEFAULT 'Other',
  photoKey VARCHAR(512) NULL,
  bio TEXT NULL,
  joinedDate TIMESTAMP NULL,
  status ENUM('active', 'former') NOT NULL DEFAULT 'active',
  displayOrder INT NOT NULL DEFAULT 0,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX team_staff_team_idx (teamId),
  INDEX team_staff_status_idx (status),
  CONSTRAINT fk_team_staff_team FOREIGN KEY (teamId) REFERENCES teams(id) ON DELETE CASCADE
);
