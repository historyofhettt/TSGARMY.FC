ALTER TABLE users ADD COLUMN xp INT NOT NULL DEFAULT 0 AFTER lastSignInAt;

CREATE TABLE xp_history (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  userId BIGINT UNSIGNED NOT NULL,
  amount INT NOT NULL,
  reason VARCHAR(255) NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX xp_history_user_idx (userId),
  CONSTRAINT fk_xp_history_user FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
);
